CLASSIFY_PROMPT = """判断以下用户请求是否为复杂任务（需要多步骤规划和工具使用）。

复杂任务特征：
- 需要创建 PPT（多页、有结构要求）
- 需要多步文件操作（读/写/生成）
- 需要先分析再执行的复合任务

简单任务特征：
- 问候、闲聊
- 简单问答
- 单步操作（如只读一个文件）

用户消息：{user_message}

请直接输出 JSON：{{"is_complex": true或false, "reason": "判断理由"}}"""

# ============================================================
# 计划创建提示词
# ============================================================

PLAN_PROMPT = """为以下用户请求创建一个详细的执行计划。

用户请求：{user_message}

可用工具：read_file, write_file, list_files, generate_ppt

请严格按照以下结构输出 JSON 对象：
{{
  "task_summary": "对整个任务的简短摘要",
  "steps": [
    {{
      "description": "具体、可执行的步骤描述",
      "expected_tools": ["可能用到的工具"]
    }}
  ],
  "estimated_difficulty": "easy、medium 或 hard"
}}

注意：
- 步骤应该具体、可执行
- 每个步骤应该有明确的输入和预期输出
- 步骤之间有逻辑依赖关系
- steps 必须至少包含一个步骤，总数不超过 {max_steps} 个
- estimated_difficulty 只能是 easy、medium 或 hard
- 不要输出 Markdown 代码块或 JSON 之外的说明文字"""

